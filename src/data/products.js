export function getProduct(slug) {
  return products.find((item) => item.slug === slug)
}

export function productsByCategory(categoryId) {
  if (!categoryId || categoryId === 'all') return products
  return products.filter((item) => item.category === categoryId)
}

export function relatedProducts(product, limit = 3) {
  const same = products.filter((item) => item.category === product.category && item.slug !== product.slug)
  const rest = products.filter((item) => item.category !== product.category && item.slug !== product.slug)
  return [...same, ...rest].slice(0, limit)
}
